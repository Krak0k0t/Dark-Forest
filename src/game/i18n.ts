function makePack(overrides: Partial<TranslationBundle>): TranslationBundle {
  return {
    ...EN,
    ...overrides,
    difficulties: { ...EN.difficulties, ...(overrides.difficulties ?? {}) },
    graphicsLevels: { ...EN.graphicsLevels, ...(overrides.graphicsLevels ?? {}) },
    mouseActions: { ...EN.mouseActions, ...(overrides.mouseActions ?? {}) },
    musicZones: { ...EN.musicZones, ...(overrides.musicZones ?? {}) },
    keyActions: { ...EN.keyActions, ...(overrides.keyActions ?? {}) },
    units: { ...EN.units, ...(overrides.units ?? {}) },
    buildings: { ...EN.buildings, ...(overrides.buildings ?? {}) },
    abilities: { ...EN.abilities, ...(overrides.abilities ?? {}) },
    upgrades: { ...EN.upgrades, ...(overrides.upgrades ?? {}) },
    relics: { ...EN.relics, ...(overrides.relics ?? {}) },
    unitShort: { ...EN.unitShort, ...(overrides.unitShort ?? {}) },
    chapters: { ...EN.chapters, ...(overrides.chapters ?? {}) },
    formations: { ...EN.formations, ...(overrides.formations ?? {}) },
    bossPhaseLabels: { ...EN.bossPhaseLabels, ...(overrides.bossPhaseLabels ?? {}) },
    bossPhaseAlerts: { ...EN.bossPhaseAlerts, ...(overrides.bossPhaseAlerts ?? {}) },
  };
}

